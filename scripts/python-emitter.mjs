/**
 * Emits the Python parity package from the same JSON Schemas that produce the
 * TypeScript types, so the AI service consumes contracts instead of
 * hand-mirroring them (roadmap milestone 0.3).
 *
 * Deliberately written in plain JS with no Python toolchain: `npm run generate`
 * stays the one command that produces everything, and a contracts change never
 * needs a Python environment to land.
 *
 * Output (generated/python/trileo_contracts/):
 *   subjects.py    SUBJECTS plus one constant per subject, byte-parity with TS
 *   models.py      TypedDicts and Literal aliases
 *   _schemas.py    the schemas themselves, embedded
 *   validation.py  runtime validators over those schemas, mirroring Ajv
 */
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const BANNER = "# Generated by scripts/generate.mjs. Do not edit.\n";

const snake = (title) =>
  title
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();

const py = (value) =>
  value === null
    ? "None"
    : typeof value === "boolean"
      ? value ? "True" : "False"
      : JSON.stringify(value);

/** Map every schema's absolute $id to its title so $refs can be resolved. */
function buildTitleIndex(schemas) {
  return new Map(schemas.map((schema) => [schema.$id, schema.title]));
}

function resolveRef(ref, baseId, titleById) {
  const absolute = new URL(ref, baseId).href;
  const title = titleById.get(absolute);
  if (!title) throw new Error(`unresolved $ref ${ref} from ${baseId}`);
  return title;
}

/** JSON Schema -> a Python type expression. */
function typeExpression(schema, baseId, titleById) {
  if (schema.$ref) return resolveRef(schema.$ref, baseId, titleById);
  if ("const" in schema) return `Literal[${py(schema.const)}]`;
  if (schema.enum) return `Literal[${schema.enum.map(py).join(", ")}]`;

  switch (schema.type) {
    case "string":
      return "str";
    case "integer":
      return "int";
    case "number":
      return "float";
    case "boolean":
      return "bool";
    case "array":
      return `list[${schema.items ? typeExpression(schema.items, baseId, titleById) : "Any"}]`;
    case "object":
      // An object with no declared properties is an open bag by design
      // (ServiceRequest.payload, ServiceError.details) — not a missing type.
      return schema.properties ? "dict[str, Any]" : "dict[str, Any]";
    default:
      return "Any";
  }
}

function emitTypedDict(name, schema, baseId, titleById, docstring) {
  const required = new Set(schema.required ?? []);
  const lines = [`class ${name}(TypedDict):`];
  if (docstring) lines.push(`    """${docstring}"""`, "");
  const properties = Object.entries(schema.properties ?? {});
  if (properties.length === 0) {
    lines.push("    pass");
    return lines.join("\n");
  }
  for (const [key, property] of properties) {
    const type = typeExpression(property, baseId, titleById);
    lines.push(`    ${key}: ${required.has(key) ? type : `NotRequired[${type}]`}`);
  }
  return lines.join("\n");
}

function emitModels(schemas, titleById) {
  const blocks = [];
  for (const schema of schemas) {
    const { title, $id: id } = schema;

    if (schema.oneOf) {
      const variants = schema.oneOf.map((variant, index) => {
        const name = `${title}Variant${index}`;
        blocks.push(emitTypedDict(name, variant, id, titleById, `One shape of ${title}.`));
        return name;
      });
      blocks.push(`${title} = ${variants.join(" | ")}`);
      continue;
    }
    if (schema.enum || "const" in schema || schema.type !== "object") {
      blocks.push(`${title} = ${typeExpression(schema, id, titleById)}`);
      continue;
    }
    blocks.push(emitTypedDict(title, schema, id, titleById));
  }

  return [
    BANNER,
    '"""Python parity types for the Trileo wire contracts.',
    "",
    "Generated from the same JSON Schemas as the TypeScript types, so the two",
    "cannot drift. TypedDicts describe shape only - use `validation` for the",
    "runtime checks (formats, lengths, patterns) that types cannot express.",
    '"""',
    "",
    "from __future__ import annotations",
    "",
    "from typing import Any, Literal, NotRequired, TypedDict",
    "",
    "",
    blocks.join("\n\n\n"),
    "",
  ].join("\n");
}

function emitSubjects(subjects) {
  const entries = Object.entries(subjects);
  const items = entries.map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  const constants = entries.map(([key, value]) => `${snake(key).toUpperCase()}: Final = ${JSON.stringify(value)}`);
  const literals = entries.map(([, value]) => JSON.stringify(value)).join(", ");

  return [
    BANNER,
    '"""NATS subject names, generated from subjects/v1.json.',
    "",
    "The authoritative list. A service that hand-copies a subject name will",
    "drift from it silently and fail as an unanswered request, so import from",
    "here instead. A breaking payload change means a NEW subject, never an",
    "edit to an existing one.",
    '"""',
    "",
    "from typing import Final",
    "",
    `SubjectName = ${literals ? `Literal[${literals}]` : "str"}`,
    "",
    "SUBJECTS: Final[dict[str, str]] = {",
    ...items,
    "}",
    "",
    ...constants,
    "",
  ].join("\n").replace("from typing import Final", "from typing import Final, Literal");
}

function emitSchemas(schemas) {
  return [
    BANNER,
    '"""The JSON Schemas themselves, embedded.',
    "",
    "Embedded rather than shipped as package data so validation works the same",
    "from a wheel, a source checkout or a container layer, with no path lookup",
    "to get wrong.",
    '"""',
    "",
    "from typing import Any, Final",
    "",
    `SCHEMAS: Final[dict[str, dict[str, Any]]] = ${toPythonLiteral(schemas.reduce((all, s) => ({ ...all, [s.$id]: s }), {}), 0)}`,
    "",
    `SCHEMA_BY_TITLE: Final[dict[str, str]] = {`,
    ...schemas.map((s) => `    ${JSON.stringify(s.title)}: ${JSON.stringify(s.$id)},`),
    "}",
    "",
  ].join("\n");
}

function toPythonLiteral(value, depth) {
  const pad = "    ".repeat(depth + 1);
  const closePad = "    ".repeat(depth);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((v) => pad + toPythonLiteral(v, depth + 1)).join(",\n")},\n${closePad}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    return `{\n${entries
      .map(([k, v]) => `${pad}${JSON.stringify(k)}: ${toPythonLiteral(v, depth + 1)}`)
      .join(",\n")},\n${closePad}}`;
  }
  return py(value);
}

function emitValidation(schemas) {
  const functions = schemas.map(
    (schema) => `def validate_${snake(schema.title)}(value: Any) -> None:
    """Raise ContractViolation unless *value* is a valid ${schema.title}."""
    _validate(${JSON.stringify(schema.$id)}, value)


def is_${snake(schema.title)}(value: Any) -> bool:
    """True when *value* is a valid ${schema.title}."""
    return _is_valid(${JSON.stringify(schema.$id)}, value)`,
  );

  return `${BANNER}"""Runtime validation against the contract schemas.

The TypeScript side compiles standalone Ajv validators; Python validates the
same schemas with jsonschema. Same schemas, same verdicts - enforced by
tests_python/test_parity.py, which runs both over the same fixtures.

Two cross-language hazards are handled here, both found by that parity suite:

  - **Unicode property escapes.** Schemas use ECMAScript regexes such as
    ^[^\\\\p{Cc}]+$ . Python's own re module cannot parse \\\\p{...} at all, so
    the pattern keyword is rebound to the regex module, which can. Without
    this, a schema that works in TypeScript raises at import time in Python.
  - **Formats are checked, not annotated.** jsonschema treats format as a
    no-op annotation by default, so a malformed email or UUID would sail
    through on the Python side while Ajv rejected it. The format checker is
    switched on explicitly.

Two shapes per contract: validate_x() raises so a caller cannot ignore a bad
payload, and is_x() returns a bool where a branch is wanted.
"""

from __future__ import annotations

from functools import lru_cache
from typing import Any

import regex
from jsonschema import Draft202012Validator, ValidationError, validators
from jsonschema import ValidationError as _JsonSchemaValidationError
from referencing import Registry, Resource

from trileo_contracts._schemas import SCHEMA_BY_TITLE, SCHEMAS

_TITLE_BY_ID = {schema_id: title for title, schema_id in SCHEMA_BY_TITLE.items()}


def _pattern(validator: Any, patrn: str, instance: Any, schema: Any):
    """The pattern keyword, on an engine that understands \\\\p{...}."""
    if validator.is_type(instance, "string") and not regex.search(patrn, instance):
        yield ValidationError(f"{instance!r} does not match {patrn!r}")


_Validator = validators.extend(Draft202012Validator, {"pattern": _pattern})


class ContractViolation(ValueError):
    """A payload does not match its contract.

    Raised at a service boundary. It means the sender is wrong, so it maps to
    VALIDATION_FAILED and is never worth retrying. The message names the
    contract and the offending field, because an error that does not turns a
    one-line fix into a debugging session.
    """

    def __init__(self, schema_id: str, error: _JsonSchemaValidationError) -> None:
        self.schema_id = schema_id
        self.title = _TITLE_BY_ID.get(schema_id, schema_id)
        self.path = list(error.absolute_path)
        location = ".".join(str(part) for part in self.path) or "<root>"
        super().__init__(f"{self.title}: {location}: {error.message}")


@lru_cache(maxsize=None)
def _registry() -> Registry:
    """All schemas in one registry so refs between them resolve."""
    return Registry().with_resources(
        (schema_id, Resource.from_contents(schema)) for schema_id, schema in SCHEMAS.items()
    )


@lru_cache(maxsize=None)
def _validator(schema_id: str) -> Draft202012Validator:
    return _Validator(
        SCHEMAS[schema_id],
        registry=_registry(),
        format_checker=_Validator.FORMAT_CHECKER,
    )


def _validate(schema_id: str, value: Any) -> None:
    try:
        _validator(schema_id).validate(value)
    except _JsonSchemaValidationError as error:
        raise ContractViolation(schema_id, error) from None


def _is_valid(schema_id: str, value: Any) -> bool:
    return _validator(schema_id).is_valid(value)


def validate_by_title(title: str, value: Any) -> None:
    """Validate against the schema with this title, e.g. "ServiceRequest"."""
    try:
        schema_id = SCHEMA_BY_TITLE[title]
    except KeyError:
        raise KeyError(f"no contract titled {title!r}") from None
    _validate(schema_id, value)


${functions.join("\n\n\n")}
`;
}

function emitInit(schemas) {
  const titles = schemas.map((s) => s.title);
  const validators = schemas.flatMap((s) => [`validate_${snake(s.title)}`, `is_${snake(s.title)}`]);
  return [
    BANNER,
    '"""Trileo wire contracts for Python.',
    "",
    "Generated from trileo_contracts/schemas/v1. Never edit by hand, and never",
    "copy a type or a subject name out of here into another repository.",
    '"""',
    "",
    "from trileo_contracts.models import *  # noqa: F403",
    "from trileo_contracts.subjects import SUBJECTS, SubjectName",
    "from trileo_contracts.validation import (",
    "    ContractViolation,",
    "    validate_by_title,",
    ...validators.map((name) => `    ${name},`),
    ")",
    "",
    "__all__ = [",
    ...["SUBJECTS", "SubjectName", "ContractViolation", "validate_by_title", ...titles, ...validators]
      .map((name) => `    ${JSON.stringify(name)},`),
    "]",
    "",
  ].join("\n");
}

export async function emitPython({ root, schemas, subjects }) {
  const packageRoot = resolve(root, "generated/python/trileo_contracts");
  await mkdir(packageRoot, { recursive: true });
  const titleById = buildTitleIndex(schemas);

  await writeFile(resolve(packageRoot, "models.py"), emitModels(schemas, titleById), "utf8");
  await writeFile(resolve(packageRoot, "subjects.py"), emitSubjects(subjects), "utf8");
  await writeFile(resolve(packageRoot, "_schemas.py"), emitSchemas(schemas), "utf8");
  await writeFile(resolve(packageRoot, "validation.py"), emitValidation(schemas), "utf8");
  await writeFile(resolve(packageRoot, "__init__.py"), emitInit(schemas), "utf8");
  await writeFile(resolve(packageRoot, "py.typed"), "", "utf8");
}
