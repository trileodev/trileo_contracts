import { readFile, readdir, mkdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compileFromFile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaRoot = resolve(root, "schemas/v1");
const outputRoot = resolve(root, "generated/typescript");

async function findJsonFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map((entry) => {
    const path = resolve(directory, entry.name);
    return entry.isDirectory() ? findJsonFiles(path) : entry.name.endsWith(".json") ? [path] : [];
  }));
  return nested.flat().sort();
}

function validatorName(title) {
  return `validate${title.replace(/[^A-Za-z0-9]/g, "")}`;
}

await mkdir(outputRoot, { recursive: true });
const schemaFiles = await findJsonFiles(schemaRoot);
const schemas = await Promise.all(schemaFiles.map(async (file) => JSON.parse(await readFile(file, "utf8"))));

const ajv = new Ajv2020({ allErrors: true, strict: true, code: { esm: true, source: true }, unicodeRegExp: true });
addFormats(ajv);
for (const schema of schemas) ajv.addSchema(schema);

const validators = Object.fromEntries(schemas.map((schema) => [validatorName(schema.title), schema.$id]));
const validatorModule = `// @ts-nocheck\n// Generated by scripts/generate.mjs. Do not edit.\n${standaloneCode(ajv, validators)}`;
await writeFile(resolve(outputRoot, "validators.ts"), validatorModule, "utf8");

const exports = [];
for (const file of schemaFiles) {
  const schema = JSON.parse(await readFile(file, "utf8"));
  const targetRelative = relative(schemaRoot, file).replace(/\.schema\.json$/, ".ts");
  const target = resolve(outputRoot, "schemas", targetRelative);
  await mkdir(dirname(target), { recursive: true });
  const source = await compileFromFile(file, {
    cwd: dirname(file),
    bannerComment: "/* Generated by scripts/generate.mjs. Do not edit. */",
    style: { singleQuote: false },
  });
  await writeFile(target, source, "utf8");
  const modulePath = targetRelative.split(sep).join("/").replace(/\.ts$/, ".js");
  exports.push(`export type { ${schema.title} } from "./schemas/${modulePath}";`);
}

const subjects = JSON.parse(await readFile(resolve(root, "subjects/v1.json"), "utf8"));
const subjectLines = Object.entries(subjects).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
await writeFile(resolve(outputRoot, "subjects.ts"), `// Generated by scripts/generate.mjs. Do not edit.\nexport const SUBJECTS = {\n${subjectLines.join("\n")}\n} as const;\nexport type SubjectName = typeof SUBJECTS[keyof typeof SUBJECTS];\n`, "utf8");
await writeFile(resolve(outputRoot, "index.ts"), `${exports.join("\n")}\nexport * from "./subjects.js";\nexport * from "./validators.js";\n`, "utf8");
